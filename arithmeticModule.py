# arithmetic operation 

def add(a,b):
    return a+b

def substract(a,b):
    # print("substraction : ",a-b)
    return a-b

def multiplication(a,b):
    return a*b
    
def division(a,b):
    return a/b
    
def modulus(a,b):
    return a%b
    
def floor_division(a,b):
    return a//b
    
